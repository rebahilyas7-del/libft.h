#include "libft.h"

int	ft_strncmp(const char *s1, const char *s2, size_t n)
{
	unsigned char	*ps1;
	unsigned char	*ps2;
	size_t			i;

	ps1 = (unsigned char *)s1;
	ps2 = (unsigned char *)s2;
	i = 0;
	if (n == 0)
		return (0);
	while ((i < n - 1) && (ps1[i]) && (ps2[i]) && (ps1[i] == ps2[i]))
	{
		i++;
	}
	return (ps1[i] - ps2[i]);
}
